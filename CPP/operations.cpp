#include<iostream>
using namespace std;
int main()
{
int a = 5;
int b = 4;

int sum = a + b;
cout<<"Sum of"<<a<< "and" <<b<< "is" <<sum<<endl;

int diff = a-b;
cout<<"Difference of" <<a<< "and" <<b<< "is" <<diff<<endl;

int mul = a*b;
cout<<"Product of" <<a<< "and" <<b<< "is" <<mul<<endl;

int div = a/b;
cout<<"Division of" <<a<< "and" <<b<< "is" <<div<<endl;

return 0;
}
